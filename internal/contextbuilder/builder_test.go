package contextbuilder

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"aicw/internal/scanner"
)

func fixture(t *testing.T) string {
	root := t.TempDir()
	w := func(rel, c string) {
		p := filepath.Join(root, rel)
		os.MkdirAll(filepath.Dir(p), 0o755)
		os.WriteFile(p, []byte(c), 0o644)
	}
	w("AGENTS.md", "# Agents\nUse tabs.\n")
	w("README.md", "# Demo\n\nA demo project.\n")
	w("go.mod", "module example.com/demo\n\ngo 1.22\n")
	w("package.json", `{"name":"web","scripts":{"test":"vitest"},"dependencies":{"react":"^19"}}`)
	w("docs/ARCHITECTURE.md", "arch notes")
	w("docs/leak.md", "token = abcdefghijklmnop1234567")
	w(".env", "SECRET=1")
	w(".claude/skills/x/SKILL.md", "---\nname: x-skill\ndescription: Does x\n---\nbody")
	return root
}

func build(t *testing.T, root string, o Options) *ContextPackage {
	s, err := scanner.Scan(root, scanner.Options{})
	if err != nil {
		t.Fatal(err)
	}
	o.Now = time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC)
	p, err := Build(root, s, o)
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func TestDeterministic(t *testing.T) {
	root := fixture(t)
	a, b := build(t, root, Options{}), build(t, root, Options{})
	if a.Markdown != b.Markdown || a.Hash != b.Hash {
		t.Fatal("package not deterministic")
	}
}

func TestContentAndExclusions(t *testing.T) {
	p := build(t, fixture(t), Options{Task: "Fix bug"})
	for _, want := range []string{"Generated by AI Context Workspace", "Go 1.22", "react@^19", "npm run test", "x-skill", "Fix bug", "verify", "AGENTS.md"} {
		if !strings.Contains(p.Markdown, want) {
			t.Errorf("missing %q", want)
		}
	}
	if strings.Contains(p.Markdown, "abcdefghijklmnop1234567") || strings.Contains(p.Markdown, "SECRET=1") {
		t.Fatal("secret leaked into context")
	}
	var leak bool
	for _, e := range p.Excluded {
		if e.Path == "docs/leak.md" {
			leak = true
		}
	}
	if !leak {
		t.Error("leaky file should be listed as excluded")
	}
}

func TestBudgetAndUserExclude(t *testing.T) {
	root := fixture(t)
	os.WriteFile(filepath.Join(root, "docs", "big.md"), []byte(strings.Repeat("word ", 20000)), 0o644)
	p := build(t, root, Options{Budget: 1500, Exclude: []string{"README.md"}})
	if p.Tokens > 1700 {
		t.Errorf("tokens %d exceed budget margin", p.Tokens)
	}
	if strings.Contains(p.Markdown, "A demo project.\n```") {
		t.Error("user-excluded README included in excerpts")
	}
	found := false
	for _, e := range p.Excluded {
		if e.Path == "README.md" && e.Reason == "excluded by user" {
			found = true
		}
	}
	if !found {
		t.Error("README exclusion not reported")
	}
}

func TestFrontmatter(t *testing.T) {
	n, d := ParseFrontmatter("---\nname: \"a\"\ndescription: b c\n---\nx")
	if n != "a" || d != "b c" {
		t.Fatalf("%q %q", n, d)
	}
}

func TestExcludedReadmeNotLeakedViaPurposeLine(t *testing.T) {
	p := build(t, fixture(t), Options{Exclude: []string{"README.md"}})
	if strings.Contains(p.Markdown, "A demo project.") {
		t.Fatal("excluded README content leaked into the identity section")
	}
}

func TestAttachedMediaListedByPathOnly(t *testing.T) {
	p := build(t, fixture(t), Options{Media: []MediaRef{{Name: "bug.png", Path: "/data/media/1/u-bug.png", Kind: "image", Note: "login button\nmisaligned"}}})
	for _, want := range []string{"Attached media", "/data/media/1/u-bug.png", "login button misaligned"} {
		if !strings.Contains(p.Markdown, want) {
			t.Errorf("missing %q", want)
		}
	}
}
