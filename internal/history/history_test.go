package history

import (
	"strings"
	"testing"
	"time"
)

func TestHandoffDoesNotInventResults(t *testing.T) {
	out := Handoff(HandoffInput{Task: "Fix login", Now: time.Date(2026, 3, 4, 5, 6, 0, 0, time.UTC)})
	for _, want := range []string{"Generated by AI Context Workspace", "Fix login", "No tests recorded", "not recorded", "verify"} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q", want)
		}
	}
	if strings.Contains(strings.ToLower(out), "tests pass.") && !strings.Contains(out, "Do not assume tests pass") {
		t.Error("must not claim passing tests")
	}
}

func TestHandoffWithData(t *testing.T) {
	out := Handoff(HandoffInput{Task: "t", Tests: []TestRun{{"go test ./...", "ok"}}, FilesChanged: []string{"a.go"}, NextSteps: "ship"})
	if !strings.Contains(out, "`go test ./...` → ok") || !strings.Contains(out, "`a.go`") || !strings.Contains(out, "ship") {
		t.Fatal(out)
	}
}

func TestFileName(t *testing.T) {
	got := FileName(time.Date(2026, 1, 2, 0, 0, 0, 0, time.UTC), "Fix: the Login/Bug!!")
	if got != "2026-01-02-fix-the-login-bug.md" {
		t.Fatal(got)
	}
	if FileName(time.Now(), "***") == "" {
		t.Fatal("empty")
	}
}
